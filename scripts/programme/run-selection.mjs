#!/usr/bin/env node
// Execute the non-Rust half of the change-aware pull selection and emit the
// Rust command file the linux lane sources.
//
// Woodpecker steps have different toolchains: the programme/registry checks
// need Node, the affected crate tests need Rust. This runner executes every
// selected non-cargo command in the Node step and writes the exact cargo
// command set to target/certification/programme/selected-cargo.sh, so BOTH
// halves derive from ONE selection document.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { lanePlan } from '../../tests/programme/lanes.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_DIR = resolve(ROOT, 'target/certification/programme');
const CARGO_FILE = resolve(OUT_DIR, 'selected-cargo.sh');

function readJson(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return null;
  }
}

function isCargo(command) {
  return /^cargo\s/.test(command) || command.startsWith('sh target/certification/programme/selected-cargo.sh');
}

function isForeignToolchain(command) {
  return command.startsWith('bash -lc "cd apps/jetbrains') || command.startsWith('./gradlew');
}

function run(command) {
  console.log(`$ ${command}`);
  const proc = spawnSync('bash', ['-lc', command], {
    cwd: ROOT,
    stdio: 'inherit',
    timeout: 60 * 60 * 1000,
    env: { ...process.env, NO_COLOR: '1' },
  });
  return proc.status === 0;
}

function main() {
  const index = process.argv.indexOf('--selection');
  const selectionPath = index >= 0 && index + 1 < process.argv.length
    ? process.argv[index + 1]
    : 'target/certification/programme/selection.json';
  const selection = readJson(resolve(ROOT, selectionPath));
  if (selection === null) {
    console.error(`run-selection: cannot read ${selectionPath}; refusing to guess`);
    return 2;
  }

  // Baseline structural suites always run (registry, selector, act-now,
  // invariants, edition8, docs). The affected Rust commands come from the
  // selection document.
  // Reuse the already-persisted selection: recomputing it would re-parse the
  // registry and re-walk every manifest for the same diff.
  const plan = lanePlan('pull', {
    changedFiles: selection.changed ?? [],
    base: selection.base ?? null,
    selection,
  });
  const baseline = plan.entries
    .filter((entry) => entry.suite !== 'affected')
    .map((entry) => entry.command);
  const commands = [...new Set([...baseline, ...(selection.commands ?? [])])];
  const cargo = commands.filter(isCargo);
  const foreign = commands.filter(isForeignToolchain);
  const node = commands.filter((command) => !isCargo(command) && !isForeignToolchain(command));

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(
    CARGO_FILE,
    `#!/bin/sh\n# Generated by run-selection.mjs from ${selectionPath}; do not edit.\nset -eu\n${cargo.join('\n')}\n`,
    { mode: 0o755 },
  );

  let failed = false;
  for (const command of node) {
    if (!run(command)) failed = true;
  }
  const document = {
    schema: 'faktor-programme-selection-run/v1',
    at: new Date().toISOString(),
    selection_digest: selection.digest,
    changed: selection.changed,
    surfaces: selection.surfaces ?? [],
    blocked_surfaces: selection.blocked_surfaces ?? [],
    deferred_crates: selection.deferred_crates ?? [],
    refused: selection.refused === true,
    fell_back: selection.fell_back ?? null,
    executed: node,
    cargo_commands: cargo,
    deferred_to_trusted: foreign.map((command) => ({ command, reason: 'PR runner has no JetBrains/Gradle toolchain; the dedicated jetbrains-build lane runs it' })),
    status: failed ? 'failed' : 'passed',
  };
  writeFileSync(resolve(OUT_DIR, 'selection-run.json'), `${JSON.stringify(document, null, 2)}\n`);
  if (failed) {
    console.error('run-selection: FAILED');
    return 1;
  }
  console.log(`run-selection: passed (${node.length} Node command(s), ${cargo.length} cargo command(s) queued)`);
  return 0;
}

process.exitCode = main();
