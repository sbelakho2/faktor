#!/usr/bin/env node
// Per-platform visual records for Edition 8. A host/platform pair is certified
// only when that platform's own harness produced the records and passed. No
// record is copied from another platform: linux/windows stay typed
// `not_certified` until their own lane runs.
//
// Output: target/certification/edition8/visual-platforms.raw.json.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { platform } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXPECTED, PLATFORMS, buildRegistry } from './registry.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const OUT = resolve(ROOT, 'target/certification/edition8');
const CURRENT = platform() === 'darwin' ? 'macos' : platform() === 'win32' ? 'windows' : 'linux';

function read(name) {
  const path = resolve(OUT, name);
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
}

// Per-platform evidence files are authoritative. The legacy single file is
// kept for the most recent run, but a reviewed macOS record and a reviewed
// Linux record must be able to coexist without one overwriting the other.
function readHost(host) {
  const documents = new Map();
  const names = [
    `visual-platforms-${host}.raw.json`,
    ...PLATFORMS.map((name) => `visual-platforms-${host}.${name}.raw.json`),
  ];
  for (const name of names) {
    const document = read(name);
    if (document !== null && typeof document.platform === 'string') {
      // Per-platform files are appended after the legacy file, so they win
      // for their own platform while the legacy file still supplies the
      // most recent run's platform.
      documents.set(document.platform, { name, document });
    }
  }
  return documents;
}

const vscode = readHost('vscode');
const jetbrains = readHost('jetbrains');
const registry = buildRegistry();
const problems = [];
const records = [];
const notCertified = [];

function hostRecord(host, documents) {
  for (const platformName of PLATFORMS) {
    const entry = documents.get(platformName) ?? null;
    const document = entry?.document ?? null;
    const reviewed = host === 'vscode'
      ? document?.manifest?.reviewed === true
      : document?.reviewed === true;
    if (document !== null && document.platform === platformName && document.counts?.failed === 0 && reviewed) {
      const cells = host === 'vscode' ? document.counts?.cells : document.cells;
      // Never synthesize a digest from a count: a record's identity is the
      // hash of the evidence it actually produced. Legacy files without a
      // digest are hashed as-written.
      const sha256 = document.sha256
        ?? `sha256:${createHash('sha256').update(JSON.stringify(document)).digest('hex')}`;
      const record = {
        host,
        platform: platformName,
        status: 'certified',
        cells,
        screens: document.counts?.screens ?? document.screens,
        build: document.build ?? document.manifest?.chrome ?? document.chrome ?? 'unknown',
        image: document.image ?? document.manifest?.image ?? null,
        os: document.os ?? document.manifest?.os ?? platformName,
        font_fingerprint: document.font_fingerprint ?? document.manifest?.font_fingerprint ?? 'host-default',
        sha256,
        source: `target/certification/edition8/${entry.name}`,
      };
      records.push(record);
    } else {
      const reason = document === null
        ? `no ${host} visual record was produced in this checkout`
        : reviewed
            ? `the ${platformName} harness recorded ${document.counts?.failed ?? 'unknown'} failures`
            : `the ${platformName} baseline was generated by the harness but is not reviewed; a reviewable ${host} ${platformName} baseline must be checked in`;
      records.push({ host, platform: platformName, status: 'not_certified', reason });
      notCertified.push(`${host}/${platformName}: ${reason}`);
    }
  }
}

hostRecord('vscode', vscode);
hostRecord('jetbrains', jetbrains);

for (const [host, documents] of [['vscode', vscode], ['jetbrains', jetbrains]]) {
  if (documents.size === 0) problems.push(`missing ${host} visual record`);
  for (const [name, entry] of documents) {
    const document = entry.document;
    if (document.counts?.failed !== 0) problems.push(`${host} visual failures ${document.counts?.failed} (${name})`);
    if (document.counts?.screens !== EXPECTED.screens) problems.push(`${host} visual screens ${document.counts?.screens} (${name})`);
  }
}
if (records.length !== EXPECTED.platform_records) problems.push(`platform records ${records.length} != ${EXPECTED.platform_records}`);
for (const record of records) {
  if (record.status !== 'certified') continue;
  if (!record.build || !record.os || !record.font_fingerprint || !record.sha256) {
    problems.push(`incomplete certified record ${record.host}/${record.platform}`);
  }
  // The record must be backed by an OS label from the same platform: a
  // macOS os string on a linux record is inherited evidence, not a render.
  const os = String(record.os).toLowerCase();
  const expected = record.platform === 'macos' ? 'darwin' : record.platform;
  if (!os.includes(expected)) {
    problems.push(`${record.host}/${record.platform} record carries os ${record.os}`);
  }
}
const certified = records.filter((record) => record.status === 'certified').length;
const certifiedPlatforms = [...new Set(records.filter((record) => record.status === 'certified').map((record) => record.platform))].sort();
const document = {
  schema: 'faktor-edition8-visual-platforms/v1',
  generated_at: new Date().toISOString(),
  current_platform: CURRENT,
  counts: {
    screens: registry.screens.length,
    hosts: 2,
    failed: problems.length,
    records: records.length,
    certified,
    certified_platforms: certifiedPlatforms,
    not_certified: records.length - certified,
  },
  detail: {
    records,
    current_platform: CURRENT,
    no_inheritance: true,
    widths: registry.required_widths,
    themes: registry.themes,
    note: 'A certified record names only the platform that rendered it. linux/windows require their own lane.',
  },
  not_certified: notCertified,
  problems,
};
mkdirSync(OUT, { recursive: true });
writeFileSync(resolve(OUT, 'visual-platforms.raw.json'), `${JSON.stringify(document, null, 2)}\n`);
for (const problem of problems) console.error(`FAIL ${problem}`);
console.log(
  `edition8 visual platforms: ${certified} certified (${certifiedPlatforms.join(', ')}), ` +
    `${records.length - certified} typed not_certified; no cross-platform inheritance`,
);
if (problems.length > 0) process.exit(1);
