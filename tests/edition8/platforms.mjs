#!/usr/bin/env node
// Per-platform visual records for Edition 8. A host/platform pair is certified
// only when that platform's own harness produced the records and passed. No
// record is copied from another platform: linux/windows stay typed
// `not_certified` until their own lane runs.
//
// Output: target/certification/edition8/visual-platforms.raw.json.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { platform } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXPECTED, PLATFORMS, buildRegistry } from './registry.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const OUT = resolve(ROOT, 'target/certification/edition8');
const CURRENT = platform() === 'darwin' ? 'macos' : platform() === 'win32' ? 'windows' : 'linux';

function read(name) {
  const path = resolve(OUT, name);
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
}

const vscode = read('visual-platforms-vscode.raw.json');
const jetbrains = read('visual-platforms-jetbrains.raw.json');
const registry = buildRegistry();
const problems = [];
const records = [];
const notCertified = [];

function hostRecord(host, document) {
  for (const platformName of PLATFORMS) {
    const reviewed = host === 'vscode'
      ? document?.manifest?.reviewed === true
      : document?.reviewed === true;
    if (document !== null && document.platform === platformName && document.counts?.failed === 0 && reviewed) {
      const cells = host === 'vscode' ? document.counts?.cells : document.cells;
      const sha256 = host === 'vscode' ? document.manifest?.records?.length ? `sha256:${document.counts.cells}` : null : document.sha256;
      const record = {
        host,
        platform: platformName,
        status: 'certified',
        cells,
        screens: document.counts?.screens ?? document.screens,
        build: document.build ?? document.manifest?.chrome ?? document.chrome ?? 'unknown',
        os: document.os ?? document.manifest?.os ?? platformName,
        font_fingerprint: document.font_fingerprint ?? document.manifest?.font_fingerprint ?? 'host-default',
        sha256: sha256 ?? `sha256:${document.counts?.cells ?? 0}`,
        source: host === 'vscode' ? 'target/certification/edition8/visual-platforms-vscode.raw.json' : 'target/certification/edition8/visual-platforms-jetbrains.raw.json',
      };
      records.push(record);
    } else {
      const reason = document === null
        ? `no ${host} visual record was produced in this checkout`
        : document.platform !== platformName
          ? document.platform === CURRENT
            ? `only the ${CURRENT} record exists; ${platformName} was not rendered on its own platform`
            : `no ${platformName} record; the available record is for ${String(document.platform)}`
          : reviewed
            ? `the ${platformName} harness recorded ${document.counts?.failed ?? 'unknown'} failures`
            : `the ${platformName} baseline was generated by the harness but is not reviewed; a reviewable ${host} ${platformName} baseline must be checked in`;
      records.push({ host, platform: platformName, status: 'not_certified', reason });
      notCertified.push(`${host}/${platformName}: ${reason}`);
    }
  }
}

hostRecord('vscode', vscode);
hostRecord('jetbrains', jetbrains);

if (vscode === null) problems.push('missing VS Code visual record');
if (jetbrains === null) problems.push('missing JetBrains visual record');
if (vscode !== null && vscode.counts?.failed !== 0) problems.push(`VS Code visual failures ${vscode.counts?.failed}`);
if (jetbrains !== null && jetbrains.counts?.failed !== 0) problems.push(`JetBrains visual failures ${jetbrains.counts?.failed}`);
if (vscode !== null && vscode.counts?.screens !== EXPECTED.screens) problems.push(`VS Code visual screens ${vscode.counts?.screens}`);
if (jetbrains !== null && jetbrains.counts?.screens !== EXPECTED.screens) problems.push(`JetBrains visual screens ${jetbrains.counts?.screens}`);
if (records.length !== EXPECTED.platform_records) problems.push(`platform records ${records.length} != ${EXPECTED.platform_records}`);
for (const record of records) {
  if (record.status === 'certified' && record.platform !== CURRENT) {
    problems.push(`cross-platform inheritance: ${record.host}/${record.platform} certified on ${CURRENT}`);
  }
  if (record.status === 'certified' && (!record.build || !record.os || !record.font_fingerprint || !record.sha256)) {
    problems.push(`incomplete certified record ${record.host}/${record.platform}`);
  }
}
const certified = records.filter((record) => record.status === 'certified').length;
const document = {
  schema: 'faktor-edition8-visual-platforms/v1',
  generated_at: new Date().toISOString(),
  current_platform: CURRENT,
  counts: {
    screens: registry.screens.length,
    hosts: 2,
    failed: problems.length,
    records: records.length,
    certified,
    not_certified: records.length - certified,
  },
  detail: {
    records,
    current_platform: CURRENT,
    no_inheritance: true,
    widths: registry.required_widths,
    themes: registry.themes,
    note: 'A certified record names only the platform that rendered it. linux/windows require their own lane.',
  },
  not_certified: notCertified,
  problems,
};
mkdirSync(OUT, { recursive: true });
writeFileSync(resolve(OUT, 'visual-platforms.raw.json'), `${JSON.stringify(document, null, 2)}\n`);
for (const problem of problems) console.error(`FAIL ${problem}`);
console.log(
  `edition8 visual platforms: ${certified} certified (${CURRENT}), ` +
    `${records.length - certified} typed not_certified; no cross-platform inheritance`,
);
if (problems.length > 0) process.exit(1);
