    private val screenById: Map<String, Edition8Screen> = screens.associateBy { it.id }
    private val controlById: Map<String, Edition8Control> = controls.associateBy { it.id }

    fun screen(id: String): Edition8Screen = screenById[id] ?: error("unknown Edition 8 screen $id")
    fun control(id: String): Edition8Control = controlById[id] ?: error("unknown Edition 8 control $id")
    fun controlsForScreen(id: String): List<Edition8Control> = screen(id).controls.map(::control)
    fun screensForControl(id: String): List<Edition8Screen> = control(id).screens.map(::screen)

    /** Frozen-count + edge gate: any missing/extra/duplicate/renamed ID fails loudly. */
    fun validate(): List<String> {
        val errors = ArrayList<String>()
        if (screens.size != SCREEN_COUNT) errors.add("screens=${screens.size}, expected $SCREEN_COUNT")
        if (controls.size != CONTROL_COUNT) errors.add("controls=${controls.size}, expected $CONTROL_COUNT")
        if (acceptance.size != ACCEPTANCE_COUNT) errors.add("acceptance=${acceptance.size}, expected $ACCEPTANCE_COUNT")
        if (workflows.size != WORKFLOW_COUNT) errors.add("workflows=${workflows.size}, expected $WORKFLOW_COUNT")
        val expectedScreens = (1..SCREEN_COUNT).map { "S%02d".format(it) }.toSet()
        val actualScreens = screens.map { it.id }.toSet()
        if (actualScreens != expectedScreens) errors.add("screen IDs drift: missing=${expectedScreens - actualScreens} extra=${actualScreens - expectedScreens}")
        if (screens.map { it.id }.distinct().size != screens.size) errors.add("duplicate screen ID")
        if (controls.map { it.id }.distinct().size != controls.size) errors.add("duplicate control ID")
        val expectedAcceptance = (1..ACCEPTANCE_COUNT).map { "A%02d".format(it) }.toSet()
        if (acceptance.map { it.id }.toSet() != expectedAcceptance) errors.add("acceptance IDs drift")
        val expectedWorkflows = (1..WORKFLOW_COUNT).map { "W%02d".format(it) }.toSet()
        if (workflows.map { it.id }.toSet() != expectedWorkflows) errors.add("workflow IDs drift")
        var edges = 0
        for (screen in screens) {
            if (screen.controls.isEmpty()) errors.add("${screen.id} has no control")
            for (controlId in screen.controls) {
                edges++
                val control = controlById[controlId] ?: run { errors.add("${screen.id} names unknown $controlId"); null }
                if (control != null && screen.id !in control.screens) errors.add("$controlId missing edge ${screen.id}")
            }
        }
        for (control in controls) {
            if (control.screens.isEmpty()) errors.add("${control.id} maps to no screen")
            for (screenId in control.screens) if (screenId !in screenById) errors.add("${control.id} names unknown $screenId")
        }
        if (edges != CONTROL_SCREEN_EDGES) errors.add("control-screen edges=$edges, expected $CONTROL_SCREEN_EDGES")
        if ((screens.size * 2) != HOST_CONTRACT_COUNT) errors.add("host contracts=${screens.size * 2}, expected $HOST_CONTRACT_COUNT")
        return errors
    }
